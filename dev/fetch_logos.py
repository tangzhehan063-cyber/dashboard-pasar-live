"""Builds src/logos.js: logo data-URIs embedded in the bundle (artifact pages can't load remote images).
Crypto: npm `cryptocurrency-icons` (CC0). US stocks: github.com/nvstly/icons ticker_icons.
Usage: python3 dev/fetch_logos.py <path-to-cryptocurrency-icons/package>"""
import base64, io, json, sys, urllib.request
from PIL import Image
CRYPTO = "BTC ETH USDT BNB SOL XRP USDC ADA DOGE TRX DOT LINK MATIC LTC BCH AVAX XLM ATOM UNI ETC FIL APT NEAR ICP ARB OP SHIB PEPE SUI TON HBAR VET ALGO AAVE MKR SAND MANA AXS GRT INJ RNDR".split()
US = ("AAPL MSFT NVDA GOOGL GOOG AMZN META TSLA AVGO BRK.B JPM V MA UNH XOM LLY JNJ WMT PG HD COST NFLX AMD INTC "
      "ORCL CRM ADBE KO PEP DIS MCD NKE BA PYPL UBER ABNB SHOP COIN PLTR SNOW SPOT BABA TSM ASML QCOM CSCO IBM "
      "SBUX T VZ PFE MRK CVX BAC WFC GS MS SPY QQQ MSTR ARM SMCI RIVN LCID SQ HOOD RBLX").split()
out = {}
pkg = sys.argv[1]
for s in CRYPTO:
    try: svg = open(f"{pkg}/svg/color/{s.lower()}.svg", "rb").read()
    except FileNotFoundError: continue
    out["c:" + s] = "data:image/svg+xml;base64," + base64.b64encode(svg).decode()
for s in US:
    try:
        raw = urllib.request.urlopen(f"https://raw.githubusercontent.com/nvstly/icons/main/ticker_icons/{s.replace('.', '-')}.png", timeout=15).read()
    except Exception:
        try: raw = urllib.request.urlopen(f"https://raw.githubusercontent.com/nvstly/icons/main/ticker_icons/{s}.png", timeout=15).read()
        except Exception: print("skip", s); continue
    im = Image.open(io.BytesIO(raw)).convert("RGBA"); im.thumbnail((64, 64), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, "PNG", optimize=True)
    out["s:" + s] = "data:image/png;base64," + base64.b64encode(b.getvalue()).decode()
with open("src/logos.js", "w") as f:
    f.write("// Generated by dev/fetch_logos.py — do not edit by hand.\nexport default " + json.dumps(out) + ";\n")
print(len(out), "logos,", sum(map(len, out.values())) // 1024, "KB")
